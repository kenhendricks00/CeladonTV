"""Generates the QR codes shown under "Support CeladonTV" in settings.

Usage: python branding/donate_qr.py   (needs `pip install segno`)

Each code is written as a VectorDrawable, so it stays sharp at any TV resolution and the app
needs no QR library. Run it again whenever a link below changes, and update the matching
donate_*_url string in app/src/main/res/values/strings.xml.
"""
from pathlib import Path

import segno

ROOT = Path(__file__).resolve().parent.parent
DRAWABLE = ROOT / "app" / "src" / "main" / "res" / "drawable"

LINKS = {
    "donate_qr_kofi": "https://ko-fi.com/kenhendricks",
    "donate_qr_bmac": "https://buymeacoffee.com/kenhendricks",
}
QUIET_ZONE = 4  # modules of white border scanners need around the code
DARK = "#0E0E10"
LIGHT = "#FFFFFF"


def vector_drawable(url):
    qr = segno.make(url, error="m", micro=False)
    rows = list(qr.matrix_iter(border=QUIET_ZONE))
    size = len(rows)
    # One horizontal run per path segment keeps the file small.
    runs = []
    for y, row in enumerate(rows):
        x = 0
        while x < size:
            if row[x]:
                start = x
                while x < size and row[x]:
                    x += 1
                runs.append(f"M{start},{y}h{x - start}v1h{start - x}z")
            else:
                x += 1
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- Generated by branding/donate_qr.py for {url}. Do not edit by hand. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:tools="http://schemas.android.com/tools"\n'
        '    android:width="160dp"\n'
        '    android:height="160dp"\n'
        f'    android:viewportWidth="{size}"\n'
        f'    android:viewportHeight="{size}"\n'
        # A long path is fine here: it's drawn once, in a dialog, and cached as a bitmap.
        '    tools:ignore="VectorPath">\n'
        f'    <path android:fillColor="{LIGHT}" android:pathData="M0,0h{size}v{size}h-{size}z" />\n'
        f'    <path android:fillColor="{DARK}" android:pathData="{"".join(runs)}" />\n'
        "</vector>\n"
    )


def main():
    for name, url in LINKS.items():
        path = DRAWABLE / f"{name}.xml"
        path.write_text(vector_drawable(url), encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
